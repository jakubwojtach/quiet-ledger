export const MESSAGES: Record<Locale, Dict> = { en, pl }

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const raw = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}
